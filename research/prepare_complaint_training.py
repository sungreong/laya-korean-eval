def row(leaf, summary, q, index, split):
    return {'id': f'{split}-{leaf}-{index:02}', 'state': f'민원 요약: {summary}', 'questions': question(q),
            'gold': {'route': {'probabilities': {k: float(k == leaf) for k in q}}},
            'metadata': {'synthetic': True, 'split': split, 'style_index': index}}


def main():
    prepare_fixture()
    DEST.mkdir(parents=True, exist_ok=True)
    fixture = ROOT / 'datasets/complaints'
    taxonomy = json.loads((fixture / 'taxonomy.json').read_text('utf-8'))
    heldout = json.loads((fixture / 'cases.json').read_text('utf-8'))
    leaves, _, questions = build_questions(taxonomy)
    q = questions['flat']
    assert set(PROFILES) == set(leaves)
    rng = random.Random(20261007)
    train, validation = [], []
    for leaf in leaves:
        situations, resolutions = PROFILES[leaf]
        for i, frame in enumerate(TRAIN_FRAMES):
            train.append(row(leaf, frame.format(s=situations[i % 6], r=resolutions[(i // 2) % 3]), q, i + 1, 'train'))
        for i, frame in enumerate(VALID_FRAMES):
            validation.append(row(leaf, frame.format(s=situations[(i + 2) % 6], r=resolutions[(i + 1) % 3]), q, i + 1, 'validation'))
    rng.shuffle(train); rng.shuffle(validation)
    texts = [r['state'] for r in train + validation]
    assert len(texts) == len(set(texts)) == 972
    assert not set(texts) & {'민원 요약: ' + r['summary'] for r in heldout}
    assert all(sum(v > 0 for v in r['gold']['route']['probabilities'].values()) == 1 for r in train + validation)
    manifest = {'generator': 'research/prepare_complaint_training.py', 'seed': 20261007,
                'source': 'author-written synthetic phrases and frames', 'heldout_fixture_used_as_training_source': False,
                'counts': {'train': len(train), 'validation': len(validation), 'per_leaf_train': 27, 'per_leaf_validation': 9},
                'diversity': {'train_surface_styles': 27, 'validation_surface_styles': 9,
                              'included_styles': ['formal web petition','call-center transcript','short memo','long context',
                                                  'indirect request','resolved distractor','mixed Korean-English','mobile shorthand','multi-issue prioritization']},
                'limitations': ['No independent human review', 'Template artifacts and shared label vocabulary may inflate results',
                                'Exact-string leakage is checked; semantic similarity is not eliminated']}
    for name, rows in [('train.jsonl', train), ('validation.jsonl', validation)]:
        payload = ''.join(json.dumps(x, ensure_ascii=False) + '\n' for x in rows)
        (DEST / name).write_text(payload, encoding='utf-8', newline='\n')
        manifest[name] = {'sha256_utf8_lf': hashlib.sha256(payload.encode()).hexdigest(), 'n': len(rows)}
    (DEST / 'manifest.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2), encoding='utf-8', newline='\n')
    print(json.dumps(manifest, ensure_ascii=False, indent=2))


if __name__ == '__main__':
    main()
