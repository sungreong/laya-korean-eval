def main():
    DEST.mkdir(parents=True, exist_ok=True)
    major_ids, middle_ids, taxonomy, cases = {}, {}, {'majors': [], 'leaves': []}, []
    for i, (major, middle, leaf, scope, *summaries) in enumerate(ROWS, 1):
        if major not in major_ids:
            major_ids[major] = f'A{len(major_ids)+1}'
            taxonomy['majors'].append({'id': major_ids[major], 'name': major, 'children': []})
        parent = next(x for x in taxonomy['majors'] if x['name'] == major)
        if (major, middle) not in middle_ids:
            middle_ids[major, middle] = f'{parent["id"]}B{len(parent["children"])+1}'
            parent['children'].append({'id': middle_ids[major, middle], 'name': middle, 'children': []})
        mid = next(x for x in parent['children'] if x['name'] == middle)
        item = {'id': f'L{i:02}', 'major_id': parent['id'], 'middle_id': mid['id'],
                'path': [major, middle, leaf], 'description': scope}
        mid['children'].append(item['id']); taxonomy['leaves'].append(item)
        for difficulty, summary in zip(['explicit','implicit','mixed_context'], summaries):
            n = len(cases)
            cases.append({'id': f'{item["id"]}-{difficulty}', 'channel': '콜센터' if n % 2 == 0 else '인터넷 상담',
                          'slice': difficulty, 'summary': summary, 'expected_leaf': item['id'],
                          'acceptable_leaves': [item['id']], 'needs_clarification': False})
    for i, (summary, accepted, question) in enumerate(AMBIGUOUS, 1):
        cases.append({'id': f'ambiguous-{i:02}', 'channel': '콜센터' if len(cases) % 2 == 0 else '인터넷 상담',
                      'slice': 'under_specified', 'summary': summary, 'expected_leaf': None,
                      'acceptable_leaves': [f'L{x:02}' for x in accepted], 'needs_clarification': True,
                      'clarification_needed': question})
    taxonomy['notes'] = '독립 검수 없는 작성자 정의의 가상 민원 분류 체계. 공식 지자체 분류표가 아님.'
    assert len(taxonomy['majors']) == 3 and len(taxonomy['leaves']) == 27 and len(cases) == 90
    assert all(len(m['children']) == 3 and all(len(n['children']) == 3 for n in m['children']) for m in taxonomy['majors'])
    for name, obj in [('taxonomy.json', taxonomy), ('cases.json', cases)]:
        (DEST / name).write_text(json.dumps(obj, ensure_ascii=False, indent=2), encoding='utf-8', newline='\n')
    print('Prepared 27 leaf categories and 90 fictional complaint summaries.')


if __name__ == '__main__':
    main()
